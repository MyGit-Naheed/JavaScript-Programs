// Type 4 = With Parameters / Arguments and with return values

//Addition
function sumOfTwoNumbers(a,b){
    return a+b;
}
let c = sumOfTwoNumbers(14,6);
console.log("Total:",c);

//Multiplication
function mullOfTwoNumbers(a1,b1){
    return a1*b1;
}
let c1 = mullOfTwoNumbers(14,6);
console.log("Total:",c1);

//Modulo
function divOfTwoNumbers(a2,b2){
    return a2%b2;
}
let c2 = divOfTwoNumbers(9,6);
console.log("Total:",c2);