// FOR LOOP
// Helps you to repeat a block of code

//ICU
//INIT = let i=0;
//CONDITION = i<10;
//UPDATION - i++

//if i <=10 is given, what will be the output

for(let i=0; i<=10;i++){
    console.log(i);
}


